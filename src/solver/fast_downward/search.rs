//! Best-first search (Sections 6.3 and 6.4 of Helmert, JAIR 2006).

use std::cmp::Ordering;
use std::collections::{BinaryHeap, HashMap, HashSet};

use anyhow::{Result, ensure};

use super::heuristics::{causal_graph_heuristic, ff_heuristic, h_max};
use super::knowledge::CompiledTask;
use super::{State, Task};

/// The result of evaluating a search state.
#[derive(Debug, Clone, PartialEq)]
pub struct Evaluation {
    /// One estimate per heuristic, in the order the problem defines them.
    pub estimates: Vec<f64>,
    /// Action ids (as returned by [`SearchProblem::successors`]) that should be
    /// preferred during search.
    pub preferred: Vec<usize>,
}

/// A successor generated by a [`SearchProblem`].
#[derive(Debug, Clone)]
pub struct Action<S> {
    /// Identifier of the action, used to match preferred actions.
    pub id: usize,
    pub state: S,
    pub cost: f64,
}

/// A state-space search problem for the generic best-first search engine.
pub trait SearchProblem {
    type State: Clone + Eq + std::hash::Hash;

    fn initial_state(&self) -> Self::State;
    fn is_goal(&self, state: &Self::State) -> bool;
    fn successors(&self, state: &Self::State) -> Vec<Action<Self::State>>;
    fn evaluate(&self, state: &Self::State) -> Evaluation;
}

/// Options shared by all best-first searches.
#[derive(Debug, Clone, PartialEq)]
pub struct SearchOptions {
    pub max_expansions: usize,
    pub max_generated: usize,
    /// Use two open lists per heuristic, the second one for preferred actions.
    pub use_preferred_operators: bool,
    /// Sort successors into the open list according to their parent's
    /// heuristic estimate; evaluate them when they are expanded (Section 6.3.2).
    pub deferred_evaluation: bool,
}

impl Default for SearchOptions {
    fn default() -> Self {
        SearchOptions {
            max_expansions: 1_000_000,
            max_generated: 5_000_000,
            use_preferred_operators: true,
            deferred_evaluation: true,
        }
    }
}

/// The outcome of a successful search.
#[derive(Debug, Clone)]
pub struct SearchOutcome<S> {
    /// Action ids along the plan.
    pub plan: Vec<usize>,
    /// Cost of the plan.
    pub cost: f64,
    /// The goal state that was reached.
    pub state: S,
    pub expanded: usize,
    pub generated: usize,
}

struct Node<S> {
    state: S,
    g: f64,
    parent: Option<usize>,
    action: Option<usize>,
    estimates: Vec<f64>,
    preferred: Vec<usize>,
    evaluated: bool,
}

#[derive(Debug, Clone, Copy)]
struct QueueEntry {
    priority: f64,
    insertion: u64,
    node: usize,
}

impl PartialEq for QueueEntry {
    fn eq(&self, other: &Self) -> bool {
        self.priority.total_cmp(&other.priority) == Ordering::Equal
            && self.insertion == other.insertion
    }
}

impl Eq for QueueEntry {}

impl PartialOrd for QueueEntry {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for QueueEntry {
    fn cmp(&self, other: &Self) -> Ordering {
        // Min-heap on priority; first-in-first-out for equal priorities.
        other
            .priority
            .total_cmp(&self.priority)
            .then_with(|| other.insertion.cmp(&self.insertion))
    }
}

/// Greedy best-first search with support for multiple heuristics, preferred
/// actions, deferred heuristic evaluation and a closed list.
pub fn best_first_search<P: SearchProblem>(
    problem: &P,
    options: &SearchOptions,
) -> Option<SearchOutcome<P::State>> {
    let initial = problem.initial_state();
    let initial_evaluation = problem.evaluate(&initial);
    let heuristic_count = initial_evaluation.estimates.len().max(1);
    let lists_per_heuristic = if options.use_preferred_operators {
        2
    } else {
        1
    };
    let mut open: Vec<BinaryHeap<QueueEntry>> =
        vec![BinaryHeap::new(); heuristic_count * lists_per_heuristic];

    let mut nodes: Vec<Node<P::State>> = vec![Node {
        state: initial.clone(),
        g: 0.0,
        parent: None,
        action: None,
        estimates: initial_evaluation.estimates.clone(),
        preferred: initial_evaluation.preferred.clone(),
        evaluated: true,
    }];
    let mut insertion = 0u64;
    for (heuristic, list) in open.iter_mut().enumerate().take(heuristic_count) {
        insertion += 1;
        list.push(QueueEntry {
            priority: initial_evaluation
                .estimates
                .get(heuristic)
                .copied()
                .unwrap_or(0.0),
            insertion,
            node: 0,
        });
    }

    let mut closed: HashMap<P::State, f64> = HashMap::new();
    let mut cursor = 0usize;
    let mut expanded = 0usize;
    let mut generated = 1usize;

    loop {
        // Pop the next node, cycling through the open lists.
        let mut entry = None;
        for attempt in 0..open.len() {
            let index = (cursor + attempt) % open.len();
            if let Some(candidate) = open[index].pop() {
                cursor = (index + 1) % open.len();
                entry = Some(candidate);
                break;
            }
        }
        let entry = entry?;

        if closed.contains_key(&nodes[entry.node].state) {
            continue;
        }
        if expanded >= options.max_expansions {
            return None;
        }

        // Deferred heuristic evaluation: evaluate the node now that it is
        // about to be expanded.
        if !nodes[entry.node].evaluated {
            let evaluation = problem.evaluate(&nodes[entry.node].state);
            nodes[entry.node].estimates = evaluation.estimates;
            nodes[entry.node].preferred = evaluation.preferred;
            nodes[entry.node].evaluated = true;
        }

        if problem.is_goal(&nodes[entry.node].state) {
            let mut plan = Vec::new();
            let mut current = Some(entry.node);
            while let Some(index) = current {
                if let Some(action) = nodes[index].action {
                    plan.push(action);
                }
                current = nodes[index].parent;
            }
            plan.reverse();
            return Some(SearchOutcome {
                plan,
                cost: nodes[entry.node].g,
                state: nodes[entry.node].state.clone(),
                expanded,
                generated,
            });
        }

        closed.insert(nodes[entry.node].state.clone(), nodes[entry.node].g);
        expanded += 1;

        let successors = problem.successors(&nodes[entry.node].state);
        let parent_estimates = nodes[entry.node].estimates.clone();
        let parent_preferred: HashSet<usize> =
            nodes[entry.node].preferred.iter().copied().collect();

        for action in successors {
            generated += 1;
            if generated > options.max_generated {
                return None;
            }
            let child_g = nodes[entry.node].g + action.cost;
            if let Some(&known) = closed.get(&action.state)
                && known <= child_g
            {
                continue;
            }
            let (estimates, preferred) = if options.deferred_evaluation {
                (parent_estimates.clone(), Vec::new())
            } else {
                let evaluation = problem.evaluate(&action.state);
                (evaluation.estimates, evaluation.preferred)
            };
            let is_preferred = parent_preferred.contains(&action.id);
            nodes.push(Node {
                state: action.state,
                g: child_g,
                parent: Some(entry.node),
                action: Some(action.id),
                estimates,
                preferred,
                evaluated: !options.deferred_evaluation,
            });
            let child = nodes.len() - 1;
            for heuristic in 0..heuristic_count {
                let priority = nodes[child]
                    .estimates
                    .get(heuristic)
                    .copied()
                    .unwrap_or(0.0);
                insertion += 1;
                open[heuristic].push(QueueEntry {
                    priority,
                    insertion,
                    node: child,
                });
                if options.use_preferred_operators && is_preferred {
                    insertion += 1;
                    open[heuristic_count + heuristic].push(QueueEntry {
                        priority,
                        insertion,
                        node: child,
                    });
                }
            }
        }
    }
}

/// The heuristics available to the planning search.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HeuristicKind {
    /// The FF heuristic with helpful actions (Section 6.2).
    Ff,
    /// The causal graph heuristic (Section 6.1).
    CausalGraph,
    /// The `h_max` estimate of the relaxed planning graph.
    Max,
}

struct PlanningProblem<'a, 'b> {
    compiled: &'a CompiledTask<'b>,
    heuristics: &'a [HeuristicKind],
}

impl SearchProblem for PlanningProblem<'_, '_> {
    type State = State;

    fn initial_state(&self) -> State {
        self.compiled.task.initial_state()
    }

    fn is_goal(&self, state: &State) -> bool {
        self.compiled.task.is_goal(state)
    }

    fn successors(&self, state: &State) -> Vec<Action<State>> {
        let task = self.compiled.task;
        self.compiled
            .successor_generator
            .applicable(state)
            .into_iter()
            .filter_map(|operator| {
                task.apply(operator, state).map(|next| Action {
                    id: operator,
                    state: next,
                    cost: task.operators[operator].cost,
                })
            })
            .collect()
    }

    fn evaluate(&self, state: &State) -> Evaluation {
        let mut estimates = Vec::with_capacity(self.heuristics.len());
        let mut preferred = Vec::new();
        for heuristic in self.heuristics {
            match heuristic {
                HeuristicKind::Ff => {
                    let value = ff_heuristic(self.compiled, state);
                    estimates.push(value.estimate);
                    preferred.extend(value.preferred);
                }
                HeuristicKind::CausalGraph => {
                    estimates.push(causal_graph_heuristic(self.compiled, state));
                }
                HeuristicKind::Max => estimates.push(h_max(self.compiled, state)),
            }
        }
        Evaluation {
            estimates,
            preferred,
        }
    }
}

/// Solve `task` with greedy best-first search and the given heuristics.
///
/// With more than one heuristic, multi-heuristic best-first search is used
/// (Section 6.4), alternating between one open list per heuristic.
pub fn search(
    task: &Task,
    heuristics: &[HeuristicKind],
    options: &SearchOptions,
) -> Result<Option<SearchOutcome<State>>> {
    ensure!(!heuristics.is_empty(), "at least one heuristic is required");
    let compiled = task.compile()?;
    let problem = PlanningProblem {
        compiled: &compiled,
        heuristics,
    };
    Ok(best_first_search(&problem, options))
}
